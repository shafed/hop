# Пути и имена, общие для install.sh и uninstall.sh.
#
# Один источник намеренно: разойдись эти два списка хоть на один путь — снятие
# оставило бы файл в системе, и I3 (§8.5) поймал бы это только на следующем
# ночном прогоне. Дублировать пути в двух скриптах дешевле ровно до первой
# правки.

PREFIX="${PREFIX:-/usr/local}"
BINDIR="$PREFIX/bin"
SBINDIR="$PREFIX/sbin"
UNIT_DIR=/etc/systemd/system
USER_UNIT_DIR=/etc/systemd/user

# Имя группы совпадает с умолчанием сервиса и агента (-group): менять его тут
# без правки обоих нечем, поэтому оно не переменная окружения.
HOP_GROUP=hop

# Системный пользователь агента (§1 С1). Это условие корректности защиты от
# петли, а не деталь установки: правило §6.8 выводит мимо туннеля всех, кто
# работает под UID агента, и раздели агент UID с человеком — мимо туннеля ушёл
# бы весь человек целиком (C25). Имя совпадает с группой намеренно: группа
# гейтит сокет, пользователь владеет каталогом, и путать их незачем.
HOP_USER=hop

DAEMON_UNIT=hopd.service
AGENT_UNIT=hop.service

# Сокет поднимает сам сервис (ipc.DefaultPath). Инсталлятор его не создаёт, но
# обязан знать путь: после снятия сервиса убитого по SIGKILL файл остаётся, а
# I3 требует, чтобы не осталось ничего.
SOCKET=/run/hop.sock

# Модуль tun грузится по требованию не везде: /dev/net/tun появляется только
# вместе с модулем, а открыть несуществующий путь автозагрузку не запускает.
# Отсюда файл modules-load.d — иначе сервис, поднявшийся при старте ОС (§6.13),
# упрётся в отсутствующее устройство.
MODULES_CONF=/etc/modules-load.d/hop.conf

die() {
	echo "hop: $*" >&2
	exit 1
}

require_root() {
	[ "$(id -u)" = 0 ] || die "нужны права root: запускать через sudo"
}

# target_user — пользователь, для которого ставится агент. Под sudo это тот,
# кто позвал установку, а не root: агент живёт без привилегий (§5.2), и его
# каталоги обязаны принадлежать человеку, а не root.
target_user() {
	if [ -n "${HOP_USER:-}" ]; then
		echo "$HOP_USER"
	elif [ -n "${SUDO_USER:-}" ] && [ "$SUDO_USER" != root ]; then
		echo "$SUDO_USER"
	else
		echo ""
	fi
}

user_home() {
	getent passwd "$1" | cut -d: -f6
}

# STORE_DIR повторяет storeDir агента (cmd/hop/paths.go) для Linux: системный
# каталог, владелец $HOP_USER, права 0700 (§2, §6.14). Заводит его юнит через
# StateDirectory=, инсталлятор только переносит в него прежний стор.
STORE_DIR=/var/lib/hop

# RUNTIME_DIR — общий каталог агента: сокет клиентов (§3.3) и приватный
# подкаталог с attach-token. Заводит его юнит через RuntimeDirectory=.
RUNTIME_DIR=/run/hop

# old_store_dir — где стор лежал до системного пользователя. Нужен ровно для
# переноса (I4, §8.5): установка поверх прежней версии обязана сохранить
# профили, а не оставить их в каталоге, куда агент больше не заглядывает.
old_store_dir() {
	echo "$(user_home "$1")/.local/share/hop"
}
