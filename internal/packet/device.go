// Package packet — граница «сервис → агент» (§3.2). Выше этой абстракции кода,
// зависящего от ОС, нет.
package packet

// PacketDevice — источник и приёмник сырых IP-пакетов.
//
// ReadPackets заполняет элементы bufs и переустанавливает их длину под
// фактический размер пакета (bufs[i] = bufs[i][:n]); вызывающий видит это
// изменение, потому что массив срезов общий. Возвращает число заполненных
// элементов. Блокируется, пока не появится хотя бы один пакет.
//
// WritePackets отдаёт пакеты устройству одним батчем.
type PacketDevice interface {
	ReadPackets(bufs [][]byte) (n int, err error)
	WritePackets(bufs [][]byte) error
	MTU() int
}
