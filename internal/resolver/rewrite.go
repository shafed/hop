package resolver

import (
	"encoding/binary"

	"github.com/shafed/hop/internal/dnsmsg"
	"github.com/shafed/hop/internal/policy"
)

// Файл резолвера, отвечающий за единственные искажения, которые разрешает У6
// регистра (docs/verification-dns.md): синтез пустого ответа на AAAA и вырез
// EDNS Client Subnet из запроса наверх. Оба искажения — часть спины запроса
// (resolver.go, serve): synthesize стоит до кэша и до апстрима, upstreamQuery
// вызывается тем, кто идёт наверх (§4, upstream.go).

// synthesize — ответ, который резолвер сочиняет сам, не спрашивая апстрим.
// nil означает «вопрос идёт наверх обычным путём».
//
// Р19: на AAAA при заблокированном IPv6 (§6.9) отвечаем пустым NOERROR, а не
// NXDOMAIN. NXDOMAIN означает «имени нет вовсе», и стаб клиента вправе
// распространить это на все типы разом — то есть заодно убить работающую
// A-запись того же имени (D46). Пустой NOERROR — единственный из вариантов,
// который приложение понимает как «здесь IPv6 нет», ровно как ведут себя сети
// без IPv6.
//
// Цена решения названа в регистре прямо, и её обязан видеть каждый, кто
// читает этот код: это ложь — `dig AAAA` через hop отвечает не то, что
// ответила бы сеть, — и в день, когда §6.9 (блокировка IPv6) отменят, эта
// строка станет неверной, и флаг dns_aaaa_nodata придётся выключить. Записи
// HTTPS/SVCB (тип 65) синтез не трогает: ipv6hint внутри них уезжает клиенту
// как есть — переписывание требует разбора и пересборки RR, от которого
// отказался C4.
func (r *Resolver) synthesize(q dnsmsg.Msg) []byte {
	if q.Question.Type != dnsmsg.TypeAAAA {
		return nil
	}
	if !policy.DNSAAAANodata.On() {
		// Флаг выключен — ведём себя так, будто синтеза нет вовсе: AAAA идёт
		// наверх обычным путём и возвращается как есть. Это ровно то
		// поведение, на котором negcheck обязан увидеть красные D45/D46.
		return nil
	}
	return dnsmsg.NoData(q)
}

// upstreamQuery — байты нашего запроса наверх: свой идентификатор,
// вырезанный ECS, объявленный буфер EDNS0 UpstreamEDNS. Свой ECS не
// добавляется.
//
// Р26: резолвер — форвардер, а не валидатор DNSSEC. DO-бит клиента (если он
// его выставил) проходит в наш запрос как есть — это то, что позволяет
// апстриму вернуть RRSIG, а дальше D50 обязан увидеть его нетронутым в ответе
// клиенту (Reply/fit копируют секции байт в байт, это уже сделано в
// upstream.go). ECS вырезаем всегда, без флага: он сообщает апстриму подсеть
// клиента, которую продукт как раз прячет, и это не переключаемая политика, а
// часть контракта (§5.6 регистра: D47–D50 без флага).
//
// Буфер EDNS0 апстриму объявляется отдельно от буфера, который резолвер
// принимает от клиента (fit, upstream.go) — тому и другому служит одно и то
// же число по разным причинам: клиенту 4096 достаётся, только если он сам его
// объявил, апстриму — всегда, чтобы получить полный ответ и решить усечение
// сами, а не унаследовать чужой мелкий буфер.
//
// Патчим на месте только существующую псевдозапись OPT: если клиент не
// объявил EDNS0 вовсе, эта функция его не собирает. Второй кодировщик
// DNS-сообщений в резолвере (в обход dnsmsg, которому эта сборка принадлежит
// по границе пакета) стоил бы дороже, чем чуть менее щедрый буфер апстриму —
// а данных о том, что это где-то проверяется, в регистре нет.
func (r *Resolver) upstreamQuery(q dnsmsg.Msg, id uint16) ([]byte, error) {
	raw := q.Raw
	copied := false

	if stripped, changed, err := dnsmsg.StripECS(q); err != nil {
		return nil, err
	} else if changed {
		raw = stripped
		copied = true
	}

	if opt, ok, err := q.EDNS(); err != nil {
		return nil, err
	} else if ok {
		if !copied {
			// StripECS ничего не резала (ECS не было или EDNS0 нет вовсе) —
			// raw всё ещё смотрит в буфер клиента, а патчить его на месте
			// нельзя: тот же буфер лежит в кэше склейки в полёте (Р24) и
			// может понадобиться другому клиенту с тем же вопросом.
			raw = append([]byte(nil), raw...)
			copied = true
		}
		// UDPSize псевдозаписи OPT лежит в поле CLASS обычной RR — том же
		// месте по смещению, но с другим смыслом (RFC 6891 §6.1.2). dnsmsg
		// отдаёт его отдельным полем OPT.UDPSize и не производит запись
		// напрямую: RR в этом пакете нужен только для копирования секций
		// байт в байт (§2 регистра, требование 7), а не для правки полей на
		// месте. Смещение считаем от RDStart, который StripECS переносит из
		// исходных координат без сдвига: префикс сообщения до RDATA он
		// копирует байт в байт, только режет опции внутри RDATA.
		classOff := opt.RDStart - 8 // CLASS(2) TTL(4) RDLENGTH(2) — восемь байт перед RDATA, класс первый из них; TYPE лежит ещё раньше и здесь не участвует
		binary.BigEndian.PutUint16(raw[classOff:classOff+2], UpstreamEDNS)
	}

	return dnsmsg.WithID(raw, id)
}
