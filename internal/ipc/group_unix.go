//go:build unix

package ipc

import (
	"fmt"
	"os/user"
	"strconv"
)

// LookupGID переводит имя группы в gid. Пустое имя — не менять группу: сокет
// остаётся доступен одному владельцу.
//
// Отсутствующая группа валит старт, а не понижается молча до 0600: процесс,
// поднявший сокет, к которому не может подключиться вторая сторона, выглядит
// рабочим и не работает. Установщик группу создаёт; в отладке и L3 передают
// -group "".
//
// Нужна обоим концам: сервис отдаёт группе `hop` управляющий сокет (§3.1), а
// агент — свой клиентский (§3.3). Второй экземпляр этой функции однажды
// разошёлся бы с первым.
func LookupGID(name string) (int, error) {
	if name == "" {
		return -1, nil
	}
	g, err := user.LookupGroup(name)
	if err != nil {
		return 0, fmt.Errorf("группа %q: %w (создать её или передать -group \"\")", name, err)
	}
	gid, err := strconv.Atoi(g.Gid)
	if err != nil {
		return 0, fmt.Errorf("группа %q: неразбираемый gid %q", name, g.Gid)
	}
	return gid, nil
}
