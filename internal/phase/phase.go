// Пакет phase — фаза трафика (§2, `TunnelState.traffic_phase`) и ничего
// больше.
//
// Почему это отдельный пакет, а не поле связки, где фаза живёт по смыслу.
// Фазу читает не только связка: резолвер этапа 6 отвечает на неё тремя разными
// способами (SERVFAIL в `failing`, удержание в `waiting`, прямой диалер в
// `bypass`), и получает её функцией `func() phase.Traffic`. Но собирает
// резолвер сама связка — значит связка импортирует резолвер, и обратный импорт
// ради одного строкового типа замкнул бы цикл. Тип, который читают все и не
// меняет никто, вынесен в лист дерева импортов.
//
// Цена — лишний пакет из десяти строк, и она осознанная: слить его обратно в
// `internal/agent` можно ровно до того момента, как оттуда потребуется импорт
// в обратную сторону.
//
// Значения строк уезжают наружу в §2 (`hop status`, IPC) и потому
// зафиксированы: менять их — ломать протокол.
package phase

// Traffic — что происходит с пакетом.
//
// Вторая половина разделения из §2. Сервисная фаза (`tunnel.Phase`) отвечает на
// вопрос «есть ли интерфейс», эта — на вопрос «что происходит с пакетом». Одно
// поле на оба не годилось: комбинация «туннель поднят, живых узлов нет»
// истинна целиком, а выражалась бы половиной.
type Traffic string

const (
	// Waiting — стартовый бюджет §5.6: ни один узел ещё не проверен, трафик
	// ждёт. Это не Failing: там знание, здесь незнание, и пользователю
	// показывать их одинаково нельзя.
	Waiting Traffic = "waiting"
	// Proxied — есть живой узел, трафик идёт через него.
	Proxied Traffic = "proxied"
	// Failing — живых узлов нет, fail-close (§5.6).
	Failing Traffic = "failing"
	// Bypass — обход включён осознанно (§1/С6). Туннель при этом снят
	// (Р35 регистра связки), поэтому Tunnel в снимке будет Down.
	Bypass Traffic = "bypass"
)
