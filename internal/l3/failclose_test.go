//go:build linux

package l3

import (
	"fmt"
	"path/filepath"
	"strings"
	"testing"
	"time"
)

// T27 — §8.4: `up`, все узлы мертвы, запрос наружу → 0 соединений на
// «интернет-сервер», доступный напрямую. Падает без fail-close на уровне TUN.
//
// Почему тест обязан быть на L3, а не уровнем ниже. T12 и T13 (internal/l2)
// проверяют, что стек **отвечает отказом** вместо молчания, — но обе половины
// утверждения T27 в них не видны. Первая: «доступный напрямую» — это про
// маршруты, и без настоящего второго интерфейса слов «напрямую» не существует.
// Вторая: «0 соединений» — про то, что пакет не ушёл никаким другим путём, а
// путей мимо туннеля в продукте два (исключения §5.6 и приёмник bypass §6.10),
// и оба живут ниже стека.
//
// Стенд обязан быть способен утечь, и здесь это показано прямо: до подъёма
// туннеля то же самое соединение доходит до пира и им засчитывается.
//
// Три утверждения, и каждое своё:
//  1. до `up` сервер достижим напрямую — иначе «0 соединений» даётся даром;
//  2. при поднятом туннеле и мёртвых узлах на сервер не пришло ничего;
//  3. приложение получило отказ, а не молчание (§5.6), и получило его быстро.
func TestT27FailCloseKeepsTrafficOffTheDirectPath(t *testing.T) {
	requireNetns(t)

	peer := startPeer(t)
	defer peer.stop()
	setupSiteNet(t)

	// Узел, который заведомо не оживёт: TCP до него доходит, VLESS за ним не
	// стоит. Это «все узлы мертвы» §5.6 в самой честной форме — узел есть,
	// адрес отвечает, живости нет.
	addNode(t, storeRoot(t), siteAddr, nodePort)

	site := fmt.Sprintf("%s:%d", siteAddr, sitePort)

	// 1. Контроль стенда: напрямую сервер достижим.
	if err, _ := connect(site, 2*time.Second); err != nil {
		t.Fatalf("«интернет-сервер» недостижим напрямую до туннеля — проверять нечего: %v", err)
	}
	// Ждать, а не сравнивать сразу: пир записывает соединение в своей горутине
	// accept, и она успевает не всегда — замер дал промах примерно на каждом
	// третьем прогоне. Промах читался бы как «стенд недостижим», то есть
	// красил бы тест ложно и ровно в том месте, где он проверяет стенд.
	waitUntil(t, 5*time.Second, "записи соединения на стороне пира", func() bool {
		return len(peer.counts(t).SiteConns) == 1
	})

	s := startService(t, orphanDeadline)
	s.startAgent(filepath.Join(t.TempDir(), "token"))

	// Туннель именно поднят, а не осиротел: отказ ниже обязан быть fail-close
	// стека, а не reject-маршрутами §6.2, которые меряет T23-fast.
	if ph := s.phase(); ph != "up" {
		t.Fatalf("phase = %q, ожидалось up", ph)
	}
	if r := tunnelRoutes(); !strings.Contains(r, "default dev "+ifname) {
		t.Fatalf("таблица туннеля не в форме up (%s) — отказ пришёл бы не от стека", r)
	}
	if got := sh("ip", "route", "get", siteAddr); !strings.Contains(got, ifname) {
		t.Fatalf("адрес сервера не забран туннелем — проверять нечего: %s", got)
	}

	// Fail-close наступает не мгновенно: пока ни один узел не проверен, §5.6
	// велит трафику ждать, а не отказывать (Р5, стартовый бюджет 30 с). Тест
	// ждёт первого раунда проб, а не спит наугад.
	var err error
	var took time.Duration
	waitUntil(t, 40*time.Second, "наступления fail-close", func() bool {
		err, took = connect(site, 2*time.Second)
		return err != nil
	})

	// 2. Собственно T27.
	if n := len(peer.counts(t).SiteConns); n != 1 {
		t.Fatalf("пир насчитал %d соединений, а до туннеля их было 1: "+
			"трафик ушёл на прямой путь мимо туннеля (fail-close §5.6 не держит)", n)
	}

	// 3. Отказ, а не молчание — та же граница, что у T23-fast и T28.
	if !isUnreachable(err) {
		t.Fatalf("отказ пришёл не отказом: %v за %v — похоже на молчаливый дроп, "+
			"а §5.6 требует RST либо ICMP unreachable", err, took)
	}
	if took > 500*time.Millisecond {
		t.Fatalf("отказ занял %v — это не отказ, а ожидание", took)
	}
	// Датаграмма — вторая половина §5.6: UDP обязан получить ICMP unreachable.
	if uerr := udpProbe(site, 500*time.Millisecond); !isUnreachable(uerr) {
		t.Fatalf("датаграмма наружу не получила отказа: %v", uerr)
	}
	t.Logf("fail-close: TCP отказал за %v (%v), UDP получил отказ, "+
		"на «интернет-сервере» по-прежнему %d соединение (то, что до туннеля)",
		took, err, len(peer.counts(t).SiteConns))
}
