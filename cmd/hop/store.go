package main

import (
	"fmt"
	"os"
	"path/filepath"
)

// storeRoot — каталог стора (Р37).
//
// Пользовательский конфиг-каталог, а не системный: стор держит ключи узлов
// (§6.14), а агент непривилегирован (§6.8) и писать ему больше некуда.
// Системный каталог потребовал бы прав и сделал бы стор общим на машину, а он
// принадлежит пользователю.
//
// Путь считается здесь, а не в internal/store: стор берёт корень аргументом
// намеренно, иначе его проверки шли бы в настоящем сторе разработчика и не
// могли бы идти параллельно (docs/verification-store.md §2, требование 3).
//
// Права 0700 выставляет сам store.Open — здесь только имя.
func storeRoot() (string, error) {
	if v := os.Getenv("HOP_STORE"); v != "" {
		// Явное переопределение — ради проверок и ради второго профиля на
		// одной машине. Не документируется как интерфейс: подкоманды этапа 9
		// решат это иначе.
		return v, nil
	}
	dir, err := os.UserConfigDir()
	if err != nil {
		return "", fmt.Errorf("не найден пользовательский каталог конфигурации: %w", err)
	}
	return filepath.Join(dir, "hop"), nil
}
