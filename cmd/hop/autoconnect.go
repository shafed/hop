package main

import (
	"fmt"

	"github.com/shafed/hop/internal/policy"
	"github.com/shafed/hop/internal/store"
)

// Автоподключение (§6.13): состояние в сторе, а не флаг агента, и правится
// глаголом `hop autoconnect on|off` — единственное исключение из «настройки
// правит файл, а не глагол» (§5.9), потому что настройка пользовательская, а
// правка агентским флагом означала бы правку unit-файла или plist под root.

// shouldAutoUp — читает §6.13 и решает, поднимать ли туннель сразу при старте
// `hop agent`.
//
// До этого прохода `run()` в main.go звало `a.Up()` безусловно — это и был
// весь смысл «автоподключение включено по умолчанию» в продукте без
// инсталлятора. §6.13 отдаёт автозапуск САМОГО СЕРВИСА/АГЕНТА инсталлятору
// (unit-файл, plist), которого в этом репозитории нет — но решение «поднимать
// ли туннель, раз уж агент запущен» инсталлятор не касается вовсе, и его
// принимает сам агент, читая стор при старте. Ровно так `applySettings`
// уже пробрасывает §6.10 и §5.7 из того же файла (W52, W53) — тот же шов,
// то же место.
//
// Функция вынесена отдельно от run(), а не встроена внутрь: run() поднимает
// настоящий TUN и требует прав, и его нельзя вызвать в обычном тесте; решение
// же — чистое чтение стора, и держать его отдельно значит проверить W67 без
// привилегий, той же ценой, какой W52/W53 проверяют applySettings.
//
// Политика autoconnect_state гасит именно это чтение: с выключенной агент
// поднимает туннель безусловно — состояние продукта до этого прохода.
func shouldAutoUp(st *store.Store) bool {
	if !policy.AutoconnectState.On() {
		return true
	}
	return st.Settings().AutoconnectOn()
}

// runAutoconnect — глагол §6.13. В сторе, а не через сокет §3.3: связка тут
// не нужна вовсе, состояние читается при следующем старте `hop agent`, а не
// прямо сейчас (в отличие от bypass/auto, которые меняют связку в памяти).
func (c *cli) runAutoconnect(_ *options, args []string) error {
	on, err := onOff("autoconnect", args)
	if err != nil {
		return err
	}
	if err := withStore(func(st *store.Store) error {
		return st.SetAutoconnect(on)
	}); err != nil {
		return err
	}
	if on {
		fmt.Fprintln(c.stdout, "автоподключение включено: следующий запуск `hop agent` поднимет туннель сам (§6.13)")
		return nil
	}
	fmt.Fprintln(c.stdout, "автоподключение выключено: следующий запуск `hop agent` будет ждать `hop up`")
	return nil
}
