//go:build unix

package main

import (
	"fmt"
	"io"
	"sync"
	"sync/atomic"

	"golang.org/x/sys/unix"
)

// tunDevice — PacketDevice поверх дескриптора, приехавшего от сервиса через
// SCM_RIGHTS (§3.2).
//
// Это агентская половина той же пары, что `internal/platform` держит на стороне
// сервиса, и написана она отдельно намеренно: platform привилегирован и умеет
// создавать интерфейс, а агенту нельзя ни того, ни другого — он получает
// готовый дескриптор и ничего больше. Общий код свёлся бы к двум системным
// вызовам, а общая зависимость затащила бы привилегированный пакет в
// непривилегированный процесс.
//
// Дескриптор держится сырым int, а не os.File, по той же причине, что и на
// стороне сервиса: os.File отдаёт его рантайму в netpoll, а этот же дескриптор
// живёт в другом процессе. Poll вручную снимает вопрос о владении опросом.
//
// Отсюда же и два поля, которых на стороне сервиса нет. Там дескриптор из-под
// читателя не закрывают вовсе — сервис им владеет и переживает агента (§3.2,
// T24), поэтому хватает флага `draining`. Здесь копия наша, закрыть её
// обязательно, и закрытие приходит из чужой горутины прямо во время чтения:
// будилка нужна, чтобы разбудить читателя, а замок — чтобы дескриптор не
// закрылся, пока читатель на нём спит.
type tunDevice struct {
	fd     int
	name   string
	mtu    int
	closed atomic.Bool

	// wakeR/wakeW — самотруба-будилка. Байт в неё будит Poll читателя, не
	// трогая сам TUN-дескриптор.
	//
	// Труба, а не eventfd: eventfd есть только на Linux, а этот файл собирается
	// на всём `unix`. Один лишний дескриптор на устройство дешевле второй
	// платформенной ветки в непривилегированном коде.
	wakeR, wakeW int

	// fdMu разделяет два права на дескриптор: работать с ним (RLock, берут
	// читатель и писатель) и закрыть его (Lock, берёт close). Именно замок, а
	// не один атомарный флаг: флаг проверяется до системного вызова, а
	// закрыться дескриптор успевает между проверкой и вызовом.
	fdMu sync.RWMutex
}

// openDevice превращает ответ сервиса в устройство.
func openDevice(fd int, name string, mtu int) (agentDevice, error) {
	if fd < 0 {
		return nil, fmt.Errorf("сервис не прислал дескриптор устройства %q", name)
	}
	// Будилка заводится здесь, а не в close: труба может не создаться
	// (упёрлись в лимит дескрипторов), и узнать об этом на закрытии значило бы
	// остаться без единственного способа разбудить читателя ровно в тот
	// момент, когда он уже спит.
	var p [2]int
	if err := unix.Pipe(p[:]); err != nil {
		return nil, fmt.Errorf("будилка для устройства %q: %w", name, err)
	}
	// CLOEXEC на обоих концах: агент запускает подпроцессы, и утёкшая туда
	// пишущая сторона держала бы будилку живой после нашего close.
	unix.CloseOnExec(p[0])
	unix.CloseOnExec(p[1])
	return &tunDevice{fd: fd, name: name, mtu: mtu, wakeR: p[0], wakeW: p[1]}, nil
}

func (d *tunDevice) MTU() int { return d.mtu }

// pollTimeout — страховка на случай, если разбудить читателя не вышло: запись
// в будилку — системный вызов, и он тоже может отказать. Без таймаута close
// ждал бы тогда читателя, которого некому разбудить, то есть навсегда. В
// обычной жизни этот таймаут не срабатывает ни разу: читателя будит труба.
const pollTimeout = 100

func (d *tunDevice) ReadPackets(bufs [][]byte) (int, error) {
	if len(bufs) == 0 {
		return 0, nil
	}
	// Замок держится на весь цикл, а не на один системный вызов: между Poll и
	// Read дескриптор точно так же нельзя закрывать, и разжать замок между
	// ними значило бы оставить ту же гонку, только уже.
	d.fdMu.RLock()
	defer d.fdMu.RUnlock()
	for {
		if d.closed.Load() {
			return 0, io.EOF
		}
		pfd := []unix.PollFd{
			{Fd: int32(d.fd), Events: unix.POLLIN},
			{Fd: int32(d.wakeR), Events: unix.POLLIN},
		}
		n, err := unix.Poll(pfd, pollTimeout)
		if err == unix.EINTR {
			continue
		}
		if err != nil {
			return 0, err
		}
		if n == 0 {
			continue
		}
		// Будилка смотрится раньше данных: закрытие важнее последнего пакета,
		// а интерфейс на той стороне сервис уже забирает.
		if pfd[1].Revents != 0 {
			return 0, io.EOF
		}
		if pfd[0].Revents == 0 {
			continue
		}
		buf := bufs[0][:cap(bufs[0])]
		got, err := unix.Read(d.fd, buf)
		if err == unix.EINTR || err == unix.EAGAIN {
			continue
		}
		if err != nil {
			return 0, err
		}
		bufs[0] = buf[:got]
		return 1, nil
	}
}

func (d *tunDevice) WritePackets(bufs [][]byte) error {
	// Тот же замок и по той же причине, что у читателя, но последствие тут
	// хуже: номер закрытого дескриптора ядро сразу отдаёт следующему open, и
	// запись без замка однажды ушла бы не в TUN, а в чужой файл — молча.
	d.fdMu.RLock()
	defer d.fdMu.RUnlock()
	if d.closed.Load() {
		return io.EOF
	}
	for _, b := range bufs {
		if _, err := unix.Write(d.fd, b); err != nil {
			return err
		}
	}
	return nil
}

// close закрывает агентскую копию дескриптора.
//
// Интерфейс PacketDevice закрываться не умеет намеренно (§3.2): устройством
// владеет тот, кто его выдал. Здесь копия **наша** — её принёс SCM_RIGHTS, и
// не закрыв её, агент утёк бы дескриптором на каждый цикл up/down.
//
// Порядок шагов — суть дела, и он такой:
//
//  1. флаг closed — читатель, ещё не дошедший до Poll, уйдёт сам;
//  2. байт в будилку — читатель, уже спящий в Poll, просыпается;
//  3. fdMu на запись — ждём, пока читатель выйдет и отпустит дескриптор;
//  4. и только теперь unix.Close.
//
// Закрыть дескриптор раньше шага 3 значит выдернуть его из-под читателя.
// Наблюдалось живьём: Poll ловил EBADF, netstack принимал это за отказ стека
// («стек остановился: bad file descriptor») и снимал датаплейн, хотя туннель
// всего лишь закрывали. Вторая половина того же — номер дескриптора уходит
// следующему open, и читатель дочитывает уже чужой файл. Охраняет W44.
func (d *tunDevice) close() error {
	if d.closed.Swap(true) {
		return nil
	}
	// Ошибка записи в будилку не разбирается: спящий читатель уйдёт по
	// pollTimeout, и это ровно то, ради чего таймаут оставлен.
	_, _ = unix.Write(d.wakeW, []byte{0})

	d.fdMu.Lock()
	defer d.fdMu.Unlock()
	err := unix.Close(d.fd)
	// Будилка закрывается после TUN и под тем же замком: читателей на ней
	// больше нет, а новый увидит closed раньше, чем дотянется до wakeR.
	unix.Close(d.wakeR)
	unix.Close(d.wakeW)
	return err
}

// closeInboundFD закрывает дескриптор, приехавший от сервиса, до того как он
// стал устройством: подъём туннеля удался, а дальше по пути что-то отказало.
// Не закрыть его значит утечь им до конца процесса — и это ещё мягкое
// следствие, потому что рядом стоит незакрытый туннель (см. transport.acquire).
func closeInboundFD(fd int) error {
	if fd < 0 {
		return nil
	}
	return unix.Close(fd)
}
